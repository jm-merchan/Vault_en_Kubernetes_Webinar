#!/usr/bin/env bash
# SCEP challenge baseline, or --cert-only for an entirely certificate-authenticated lifecycle.
# Uses Bash, Vault CLI, OpenSSL, curl, jq and a small Go CMS helper. No Python.
if [[ -f /tmp/vault/config.env ]]; then
  set -a
  # shellcheck disable=SC1091
  source /tmp/vault/config.env
  set +a
fi
set -euo pipefail
umask 077
unset VAULT_NAMESPACE
: "${VAULT_ADDR:?}" "${VAULT_TOKEN:?}" "${VAULT_CACERT:?}"
SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO_DIR=$(dirname "$SCRIPT_DIR")
RUN_ID=$(date -u +%Y%m%dT%H%M%SZ)
CERT_ONLY=false
if [[ "${1:-}" == --cert-only && $# == 1 ]]; then
  CERT_ONLY=true
elif [[ $# != 0 ]]; then
  printf 'Usage: %s [--cert-only]\n' "$0" >&2
  exit 1
fi
SCEP_TEST_CERT_AUTH=${SCEP_TEST_CERT_AUTH:-true}
[[ "$CERT_ONLY" == false ]] || SCEP_TEST_CERT_AUTH=true
case "$SCEP_TEST_CERT_AUTH" in true|false) ;; *) printf 'SCEP_TEST_CERT_AUTH must be true or false\n' >&2; exit 1 ;; esac
EVIDENCE_PREFIX=scep-shared-credential
[[ "$SCEP_TEST_CERT_AUTH" == false ]] || EVIDENCE_PREFIX=scep-auth-methods
[[ "$CERT_ONLY" == false ]] || EVIDENCE_PREFIX=scep-cert-only
EVIDENCE_DIR="$REPO_DIR/evidence/$EVIDENCE_PREFIX-$RUN_ID"
WORKDIR=$(mktemp -d /tmp/vault-scep-cli.XXXXXX)
PKI="pki_scep_cli_${RUN_ID}"
AUTH="scep-cli-${RUN_ID}"
CERT_AUTH="scep-cert-cli-${RUN_ID}"
POLICY="scep-cli-$(printf '%s' "$RUN_ID" | tr '[:upper:]' '[:lower:]')"
AUDIT="scep-cli-${RUN_ID}"
AUDIT_FILE="/tmp/${AUDIT}.json"
KUBE_CONTEXT=${KUBE_CONTEXT:-workshop-k8s}
KUBE_NAMESPACE=${KUBE_NAMESPACE:-vault}
OPENSSL_BIN=${OPENSSL_BIN:-/opt/homebrew/opt/openssl@3/bin/openssl}
[[ -x "$OPENSSL_BIN" ]] || OPENSSL_BIN=openssl
mkdir -p "$EVIDENCE_DIR/certificates"
CREATED_PKI=false CREATED_AUTH=false CREATED_CERT_AUTH=false CREATED_POLICY=false CREATED_AUDIT=false
CERT_ACCESSOR=""
ACCESSOR=""
CERT_COMPARISON='{"tested":false}'
EXPECTED_SUCCESS=4
EXPECTED_CERTIFICATES=5
SUCCESS_STEPS=()

vault() { command vault "$@"; }
log() { printf '%s\n' "$*"; }
assert() { if ! "$@"; then log "FAILED: $*" >&2; exit 1; fi; }
checkpoint() {
  vault read -format=json sys/internal/counters/activity > "$EVIDENCE_DIR/activity-$1.json"
  jq -n --arg phase "$1" --slurpfile data "$EVIDENCE_DIR/activity-$1.json" \
    '{phase:$phase,clients:$data[0].data.total}' >> "$EVIDENCE_DIR/phases.jsonl"
}

collect_audit() {
  local pod
  for pod in $(kubectl --context "$KUBE_CONTEXT" -n "$KUBE_NAMESPACE" get pods -l app.kubernetes.io/name=vault -o name); do
    kubectl --context "$KUBE_CONTEXT" -n "$KUBE_NAMESPACE" exec "${pod#pod/}" -c vault -- \
      sh -c "test ! -f '$AUDIT_FILE' || cat '$AUDIT_FILE'" 2>/dev/null
  done | jq -c --arg path "$PKI/roles/devices/scep" --arg login "auth/$AUTH/login" --arg cert_login "auth/$CERT_AUTH/login" '
    select(.request.path == $path or .request.path == $login or .request.path == $cert_login)
    | {time,type,request_id:.request.id,path:.request.path,operation:.request.operation,
       client_id:(.request.client_id // .auth.client_id // null),entity_id:(.auth.entity_id // null),
       display_name:(.auth.display_name // null),policies:(.auth.policies // []),
       token_type:(.auth.token_type // null),http_status:(.response.data.http_status_code // null),
       error:(.error // null)}' > "$EVIDENCE_DIR/audit-redacted.jsonl"
}

cleanup() (
  set +e
  [[ "$CREATED_CERT_AUTH" == false ]] || vault auth disable "$CERT_AUTH" >/dev/null
  [[ "$CREATED_AUTH" == false ]] || vault auth disable "$AUTH" >/dev/null
  [[ "$CREATED_PKI" == false ]] || vault secrets disable "$PKI" >/dev/null
  [[ "$CREATED_POLICY" == false ]] || vault policy delete "$POLICY" >/dev/null
  [[ "$CREATED_AUDIT" == false ]] || vault audit disable "$AUDIT" >/dev/null
  # Exact mktemp directory generated by this process; contains lab keys/challenges.
  if [[ "$WORKDIR" == /tmp/vault-scep-cli.* && -d "$WORKDIR" ]]; then
    find "$WORKDIR" -type f -delete
    rmdir "$WORKDIR"
  fi
)
on_exit() {
  local rc=$?
  trap - EXIT
  if [[ "$CREATED_AUDIT" == true ]]; then collect_audit || true; fi
  cleanup
  exit "$rc"
}
trap on_exit EXIT

log "SCEP evidence: $EVIDENCE_DIR"
(cd "$SCRIPT_DIR/scep-message" && GOPROXY=off GOSUMDB=off go build -o "$WORKDIR/scep-message" .)
vault status -format=json | jq '{version,sealed,cluster_name}' > "$EVIDENCE_DIR/vault-status.json"
vault read -format=json sys/internal/counters/activity > "$EVIDENCE_DIR/activity-before.json"
vault read -format=json sys/billing/certificates > "$EVIDENCE_DIR/certificates-before.json"
# Refuse name collisions. Cleanup is never used as a preflight.
assert jq -e --arg p "$PKI/" 'has($p)|not' < <(vault secrets list -format=json)
assert jq -e --arg p "$AUTH/" 'has($p)|not' < <(vault auth list -format=json)
assert jq -e --arg p "$CERT_AUTH/" 'has($p)|not' < <(vault auth list -format=json)
vault audit enable -path="$AUDIT" file file_path="$AUDIT_FILE" log_raw=false >/dev/null
CREATED_AUDIT=true
vault secrets enable -path="$PKI" pki >/dev/null
CREATED_PKI=true
vault secrets tune -max-lease-ttl=24h "$PKI" >/dev/null
# A dedicated short-lived issuing root is sufficient for this isolated lab.
vault write -format=json "$PKI/root/generate/internal" common_name="SCEP CLI Test CA $RUN_ID" \
  key_type=rsa key_bits=2048 ttl=24h > "$WORKDIR/ca-response.json"
jq -r .data.certificate "$WORKDIR/ca-response.json" > "$EVIDENCE_DIR/certificates/ca.pem"
CA="$EVIDENCE_DIR/certificates/ca.pem"
vault write "$PKI/roles/devices" allowed_domains=scep-cli.example.test allow_subdomains=true \
  allow_bare_domains=false allow_ip_sans=false allow_wildcard_certificates=false \
  key_type=rsa key_bits=2048 client_flag=true server_flag=false ttl=1h max_ttl=2h \
  use_csr_common_name=true use_csr_sans=true no_store=false >/dev/null
printf 'path "%s/roles/devices/scep" { capabilities = ["read", "create", "update"] }\n' "$PKI" \
  | vault policy write "$POLICY" - >/dev/null
CREATED_POLICY=true
if [[ "$CERT_ONLY" == false ]]; then
vault auth enable -path="$AUTH" scep >/dev/null
CREATED_AUTH=true
vault auth tune -token-type=batch "$AUTH" >/dev/null
"$OPENSSL_BIN" rand -hex 32 | tr -d '\n' > "$WORKDIR/challenge"
vault write "auth/$AUTH/role/shared-fleet" auth_type=static-challenge \
  challenge=@"$WORKDIR/challenge" token_type=batch token_ttl=5m \
  token_no_default_policy=true token_policies="$POLICY" >/dev/null
ACCESSOR=$(vault read -field=accessor "sys/auth/$AUTH")
vault secrets tune -delegated-auth-accessors="$ACCESSOR" "$PKI" >/dev/null
jq -n --arg accessor "$ACCESSOR" '{enabled:true,default_path_policy:"role:devices",
  restrict_ca_chain_to_issuer:true,authenticators:{scep:{accessor:$accessor,scep_role:"shared-fleet"}},
  allowed_digest_algorithms:["sha-256"],allowed_encryption_algorithms:["aes256-cbc"]}' \
  | vault write -format=json "$PKI/config/scep" - > "$EVIDENCE_DIR/scep-config.json"
vault read -format=json "auth/$AUTH/role/shared-fleet" > "$EVIDENCE_DIR/auth-role.json"
fi
if [[ "$SCEP_TEST_CERT_AUTH" == true ]]; then
  vault auth enable -path="$CERT_AUTH" cert >/dev/null
  CREATED_CERT_AUTH=true
  vault auth tune -token-type=batch "$CERT_AUTH" >/dev/null
  vault write "auth/$CERT_AUTH/certs/devices" certificate=@"$CA" \
    allowed_common_names='device-*.scep-cli.example.test' \
    allowed_dns_sans='device-*.scep-cli.example.test' \
    token_type=batch token_ttl=5m token_no_default_policy=true token_policies="$POLICY" >/dev/null
  CERT_ACCESSOR=$(vault read -field=accessor "sys/auth/$CERT_AUTH")
  DELEGATED_ARGS=(-delegated-auth-accessors="$CERT_ACCESSOR")
  if [[ -n "$ACCESSOR" ]]; then DELEGATED_ARGS+=(-delegated-auth-accessors="$ACCESSOR"); fi
  vault secrets tune "${DELEGATED_ARGS[@]}" "$PKI" >/dev/null
  jq -n --arg scep "$ACCESSOR" --arg cert "$CERT_ACCESSOR" \
    '{enabled:true,default_path_policy:"role:devices",restrict_ca_chain_to_issuer:true,
      authenticators:({cert:{accessor:$cert,cert_role:"devices"}} +
        if $scep=="" then {} else {scep:{accessor:$scep,scep_role:"shared-fleet"}} end),
      allowed_digest_algorithms:["sha-256"],allowed_encryption_algorithms:["aes256-cbc"]}' \
    | vault write -format=json "$PKI/config/scep" - > "$EVIDENCE_DIR/scep-config.json"
  vault read -format=json "auth/$CERT_AUTH/certs/devices" > "$EVIDENCE_DIR/cert-auth-role.json"
  vault read -format=json "auth/$CERT_AUTH/config" > "$EVIDENCE_DIR/cert-auth-config.json"
fi
URL="$VAULT_ADDR/v1/$PKI/roles/devices/scep"
jq -n --arg url "$URL" --arg pki "$PKI" --arg auth "$AUTH" --arg policy "$POLICY" \
  --arg audit "$AUDIT" --arg accessor "$ACCESSOR" --arg cert_auth "$CERT_AUTH" --arg cert_accessor "$CERT_ACCESSOR" --argjson cert_only "$CERT_ONLY" \
  '{url:$url,pki_mount:$pki,auth_mount:(if $accessor=="" then null else $auth end),policy:$policy,audit:$audit,auth_accessor:$accessor,namespace:"root",
    auth_type:(if $cert_only then "cert-only" else "static-challenge" end),
    cert_auth_mount:(if $cert_accessor=="" then null else $cert_auth end),cert_auth_accessor:$cert_accessor}' \
  > "$EVIDENCE_DIR/resources.json"

HTTP=$(curl --silent --show-error --cacert "$VAULT_CACERT" -o "$EVIDENCE_DIR/getcacaps.txt" \
  -w '%{http_code}' "$URL?operation=GetCACaps")
assert test "$HTTP" = 200
HTTP=$(curl --silent --show-error --cacert "$VAULT_CACERT" -D "$EVIDENCE_DIR/getcacert.headers" \
  -o "$WORKDIR/ca.der" -w '%{http_code}' "$URL?operation=GetCACert")
assert test "$HTTP" = 200
"$OPENSSL_BIN" x509 -inform DER -in "$WORKDIR/ca.der" -out "$WORKDIR/ca-from-scep.pem"
assert test "$("$OPENSSL_BIN" x509 -in "$CA" -noout -fingerprint -sha256)" = \
  "$("$OPENSSL_BIN" x509 -in "$WORKDIR/ca-from-scep.pem" -noout -fingerprint -sha256)"

make_csr() {
  local name=$1 cn=$2 challenge=$3
  # Generated runtime data; no private challenge is copied to evidence.
  if [[ -n "$challenge" ]]; then
    printf '[req]\nprompt=no\ndistinguished_name=dn\nattributes=attrs\nreq_extensions=ext\n[dn]\nCN=%s\n[attrs]\nchallengePassword=%s\n[ext]\nsubjectAltName=DNS:%s\n' \
      "$cn" "$challenge" "$cn" > "$WORKDIR/$name.cnf"
  else
    printf '[req]\nprompt=no\ndistinguished_name=dn\nreq_extensions=ext\n[dn]\nCN=%s\n[ext]\nsubjectAltName=DNS:%s\n' \
      "$cn" "$cn" > "$WORKDIR/$name.cnf"
  fi
  "$OPENSSL_BIN" req -new -newkey rsa:2048 -nodes -sha256 -keyout "$WORKDIR/$name.key" \
    -out "$WORKDIR/$name.csr" -config "$WORKDIR/$name.cnf" >/dev/null 2>&1
}

send_request() {
  local name=$1 type=$2 signer_cert=$3 signer_key=$4 expected=$5 expected_auth=${6:-scep} rc=0
  local signer_serial signer_sha256 signer_pubkey csr_pubkey signer_subject csr_subject signer_san csr_san
  signer_serial=$("$OPENSSL_BIN" x509 -in "$signer_cert" -noout -serial | cut -d= -f2)
  signer_sha256=$("$OPENSSL_BIN" x509 -in "$signer_cert" -outform DER | "$OPENSSL_BIN" dgst -sha256 -r | awk '{print $1}')
  signer_pubkey=$("$OPENSSL_BIN" x509 -in "$signer_cert" -noout -pubkey | "$OPENSSL_BIN" dgst -sha256 -r | awk '{print $1}')
  csr_pubkey=$("$OPENSSL_BIN" req -in "$WORKDIR/$name.csr" -noout -pubkey | "$OPENSSL_BIN" dgst -sha256 -r | awk '{print $1}')
  if [[ "$CERT_ONLY" == true ]]; then
    cp "$WORKDIR/$name.csr" "$EVIDENCE_DIR/$name.csr.pem"
    if [[ "$expected" == success ]]; then
      "$OPENSSL_BIN" verify -purpose sslclient -CAfile "$CA" "$signer_cert" >/dev/null
      signer_subject=$("$OPENSSL_BIN" x509 -in "$signer_cert" -noout -subject -nameopt RFC2253)
      csr_subject=$("$OPENSSL_BIN" req -in "$WORKDIR/$name.csr" -noout -subject -nameopt RFC2253)
      assert test "$signer_subject" = "$csr_subject"
      signer_san=$("$OPENSSL_BIN" x509 -in "$signer_cert" -noout -ext subjectAltName | tail -n 1 | sed 's/^[[:space:]]*//')
      csr_san=$("$OPENSSL_BIN" req -in "$WORKDIR/$name.csr" -noout -text | sed -n '/X509v3 Subject Alternative Name:/{n;s/^[[:space:]]*//;p;}')
      assert test "$signer_san" = "$csr_san"
      assert test "$signer_pubkey" != "$csr_pubkey"
    fi
  fi
  "$WORKDIR/scep-message" prepare -type "$type" -csr "$WORKDIR/$name.csr" \
    -ca "$CA" -signer-cert "$signer_cert" -signer-key "$signer_key" \
    -out "$WORKDIR/$name-request.der" > "$EVIDENCE_DIR/$name-request.json"
  # No Vault token is sent: authentication occurs inside the SCEP message.
  local http
  http=$(curl --silent --show-error --cacert "$VAULT_CACERT" \
    -H 'Content-Type: application/x-pki-message' --data-binary @"$WORKDIR/$name-request.der" \
    -D "$EVIDENCE_DIR/$name.headers" -o "$WORKDIR/$name-response.der" \
    -w '%{http_code}' "$URL?operation=PKIOperation")
  assert test "$http" = 200
  "$WORKDIR/scep-message" verify -csr "$WORKDIR/$name.csr" -ca "$CA" \
    -signer-cert "$signer_cert" -signer-key "$signer_key" \
    -request "$WORKDIR/$name-request.der" -response "$WORKDIR/$name-response.der" \
    -out "$EVIDENCE_DIR/certificates/$name.pem" > "$EVIDENCE_DIR/$name-result.json" || rc=$?
  if [[ "$expected" == failure ]]; then
    assert test "$rc" = 2
    assert jq -e '.pki_status == "2" and .signature_verified' "$EVIDENCE_DIR/$name-result.json"
  else
    assert test "$rc" = 0
    assert jq -e '.pki_status == "0" and .signature_verified and .nonce_verified' "$EVIDENCE_DIR/$name-result.json"
    "$OPENSSL_BIN" verify -CAfile "$CA" "$EVIDENCE_DIR/certificates/$name.pem" >/dev/null
    "$OPENSSL_BIN" x509 -in "$EVIDENCE_DIR/certificates/$name.pem" -noout -subject -issuer -serial -dates -ext subjectAltName \
      > "$EVIDENCE_DIR/$name-certificate.txt"
    # Keep public, encrypted protocol envelopes for independent inspection.
    cp "$WORKDIR/$name-request.der" "$EVIDENCE_DIR/$name-request.der"
    cp "$WORKDIR/$name-response.der" "$EVIDENCE_DIR/$name-response.der"
    SUCCESS_STEPS+=("$name")
  fi
  jq -n --arg step "$name" --arg auth "$expected_auth" --arg expected "$expected" \
    --arg signer_reference "$(basename "$signer_cert" .pem)" --arg signer_serial "$signer_serial" \
    --arg signer_sha256 "$signer_sha256" --arg signer_pubkey "$signer_pubkey" --arg csr_pubkey "$csr_pubkey" \
    --argjson http "$http" --slurpfile request "$EVIDENCE_DIR/$name-request.json" \
    --slurpfile result "$EVIDENCE_DIR/$name-result.json" \
    '{step:$step,expected_auth:$auth,expected_result:$expected,http_status:$http,request:$request[0],result:$result[0],
      signer_reference:$signer_reference,signer_serial:$signer_serial,signer_sha256:$signer_sha256,
      signer_public_key_sha256:$signer_pubkey,csr_public_key_sha256:$csr_pubkey}' \
    >> "$EVIDENCE_DIR/request-results.jsonl"
  log "$name: HTTP=$http messageType=$type pkiStatus=$(jq -r .pki_status "$EVIDENCE_DIR/$name-result.json")"
}

if [[ "$CERT_ONLY" == true ]]; then
  # Provision existing per-device credentials via the administrative PKI API.
  # No SCEP challenge or SCEP auth mount exists in this mode.
  checkpoint baseline
  for i in 01 02 03; do
    name="bootstrap-$i"
    make_csr "$name" "device-$i.scep-cli.example.test" ""
    cp "$WORKDIR/$name.csr" "$EVIDENCE_DIR/$name.csr.pem"
    vault write -format=json "$PKI/sign/devices" csr=@"$WORKDIR/$name.csr" ttl=1h \
      | jq -r .data.certificate > "$EVIDENCE_DIR/certificates/$name.pem"
  done
  checkpoint after-bootstrap
  # RFC 8894: existing-certificate authentication uses RenewalReq (17), even
  # when this is the device's first SCEP request to the service.
  for i in 01 02 03; do
    name="cert-first-$i"
    make_csr "$name" "device-$i.scep-cli.example.test" ""
    send_request "$name" 17 "$EVIDENCE_DIR/certificates/bootstrap-$i.pem" "$WORKDIR/bootstrap-$i.key" success cert
    checkpoint "$name"
  done
  checkpoint after-enroll
  for i in 01 02 03; do
    name="cert-renew1-$i"
    make_csr "$name" "device-$i.scep-cli.example.test" ""
    send_request "$name" 17 "$EVIDENCE_DIR/certificates/cert-first-$i.pem" "$WORKDIR/cert-first-$i.key" success cert
    checkpoint "$name"
  done
  checkpoint after-renew
  for i in 01 02 03; do
    name="cert-renew2-$i"
    make_csr "$name" "device-$i.scep-cli.example.test" ""
    send_request "$name" 17 "$EVIDENCE_DIR/certificates/cert-renew1-$i.pem" "$WORKDIR/cert-renew1-$i.key" success cert
    checkpoint "$name"
  done
  checkpoint after-renew2
  make_csr untrusted-cert device-01.scep-cli.example.test ""
  "$OPENSSL_BIN" x509 -req -in "$WORKDIR/untrusted-cert.csr" -signkey "$WORKDIR/untrusted-cert.key" \
    -sha256 -days 1 -out "$WORKDIR/untrusted-cert-self.pem" >/dev/null 2>&1
  send_request untrusted-cert 17 "$WORKDIR/untrusted-cert-self.pem" "$WORKDIR/untrusted-cert.key" failure cert
  checkpoint after-controls
  EXPECTED_SUCCESS=9
  EXPECTED_CERTIFICATES=13
else
CHALLENGE=$(<"$WORKDIR/challenge")
for i in 01 02 03; do
  name="device-$i"
  make_csr "$name" "$name.scep-cli.example.test" "$CHALLENGE"
  "$OPENSSL_BIN" x509 -req -in "$WORKDIR/$name.csr" -signkey "$WORKDIR/$name.key" \
    -sha256 -days 1 -out "$WORKDIR/$name-self.pem" >/dev/null 2>&1
  send_request "$name" 19 "$WORKDIR/$name-self.pem" "$WORKDIR/$name.key" success
done
vault read -format=json sys/internal/counters/activity > "$EVIDENCE_DIR/activity-after-enroll.json"
collect_audit

make_csr device-01-renewed device-01.scep-cli.example.test "$CHALLENGE"
send_request device-01-renewed 17 "$EVIDENCE_DIR/certificates/device-01.pem" "$WORKDIR/device-01.key" success
vault read -format=json sys/internal/counters/activity > "$EVIDENCE_DIR/activity-after-renew.json"

make_csr wrong-challenge wrong-challenge.scep-cli.example.test "incorrect-$RUN_ID"
"$OPENSSL_BIN" x509 -req -in "$WORKDIR/wrong-challenge.csr" -signkey "$WORKDIR/wrong-challenge.key" \
  -sha256 -days 1 -out "$WORKDIR/wrong-challenge-self.pem" >/dev/null 2>&1
send_request wrong-challenge 19 "$WORKDIR/wrong-challenge-self.pem" "$WORKDIR/wrong-challenge.key" failure
vault read -format=json sys/internal/counters/activity > "$EVIDENCE_DIR/activity-after-challenge-negative.json"

if [[ "$SCEP_TEST_CERT_AUTH" == true ]]; then
  for i in 01 02 03; do
    name="device-$i-cert-renewed"
    make_csr "$name" "device-$i.scep-cli.example.test" ""
    send_request "$name" 17 "$EVIDENCE_DIR/certificates/device-$i.pem" "$WORKDIR/device-$i.key" success cert
  done
  vault read -format=json sys/internal/counters/activity > "$EVIDENCE_DIR/activity-after-cert-renew.json"
  make_csr device-01-cert-renewed-again device-01.scep-cli.example.test ""
  send_request device-01-cert-renewed-again 17 "$EVIDENCE_DIR/certificates/device-01-cert-renewed.pem" \
    "$WORKDIR/device-01-cert-renewed.key" success cert
  vault read -format=json sys/internal/counters/activity > "$EVIDENCE_DIR/activity-after-cert-repeat.json"

  # A self-signed device certificate must not pass the configured CA trust.
  make_csr untrusted-cert device-02.scep-cli.example.test ""
  send_request untrusted-cert 17 "$WORKDIR/device-02-self.pem" "$WORKDIR/device-02.key" failure cert
  # A valid signing cert must not bypass an explicitly wrong challenge.
  make_csr trusted-cert-wrong-challenge device-03.scep-cli.example.test "incorrect-$RUN_ID"
  send_request trusted-cert-wrong-challenge 17 "$EVIDENCE_DIR/certificates/device-03.pem" \
    "$WORKDIR/device-03.key" failure scep
  vault read -format=json sys/internal/counters/activity > "$EVIDENCE_DIR/activity-after-cert-negatives.json"
  EXPECTED_SUCCESS=8
  EXPECTED_CERTIFICATES=9
fi
fi
collect_audit

jq -s '[.[]|select(.type=="response" and .http_status==200 and .client_id!=null and .token_type=="batch" and .error==null)]
  | unique_by(.request_id) | {successful_responses:length,request_ids:map(.request_id),
      client_ids:(map(.client_id)|unique),entity_ids:(map(.entity_id)|unique),
      display_names:(map(.display_name)|unique),token_types:(map(.token_type)|unique)}' \
  "$EVIDENCE_DIR/audit-redacted.jsonl" > "$EVIDENCE_DIR/identity-correlation.json"
assert jq -e --argjson expected "$EXPECTED_SUCCESS" '.successful_responses == $expected and (.client_ids|all(.!=null and .!=""))' "$EVIDENCE_DIR/identity-correlation.json"
for entity_id in $(jq -r '.entity_ids[]|select(.!=null)' "$EVIDENCE_DIR/identity-correlation.json"); do
  vault read -format=json "identity/entity/id/$entity_id" \
    | jq '.data|{id,name,aliases:[.aliases[]|{name,mount_accessor,mount_path,mount_type,canonical_id}]}'
done | jq -s . > "$EVIDENCE_DIR/entity-aliases.json"
printf '%s\n' "${SUCCESS_STEPS[@]}" | jq -R . | jq -s . > "$EVIDENCE_DIR/successful-steps.json"
jq -s --slurpfile steps "$EVIDENCE_DIR/successful-steps.json" '[.[]|select(.type=="response" and .http_status==200 and .client_id!=null and .token_type=="batch" and .error==null)]
  | unique_by(.request_id) | sort_by(.time)
  | to_entries | map(. as $entry | $entry.value + {step:$steps[0][$entry.key]})' \
  "$EVIDENCE_DIR/audit-redacted.jsonl" > "$EVIDENCE_DIR/operations.json"
jq -s '[.[]|select(.expected_result=="success")|.result]
  | {certificates:.,unique_serials:(map(.serial)|unique|length),unique_fingerprints:(map(.sha256)|unique|length)}' \
  "$EVIDENCE_DIR/request-results.jsonl" \
  > "$EVIDENCE_DIR/certificate-results.json"
assert jq -e --argjson expected "$EXPECTED_SUCCESS" '.unique_serials==$expected and .unique_fingerprints==$expected' "$EVIDENCE_DIR/certificate-results.json"

# Prove the actual delegated path for each successful operation, not only success.
jq -n --slurpfile operations "$EVIDENCE_DIR/operations.json" --slurpfile audit "$EVIDENCE_DIR/audit-redacted.jsonl" \
  --slurpfile requests "$EVIDENCE_DIR/request-results.jsonl" --arg scep "auth/$AUTH/login" --arg cert "auth/$CERT_AUTH/login" '
  [$operations[0][] as $op | ($requests[]|select(.step==$op.step)) as $request
   | [$audit[]|select(.request_id==$op.request_id and .type=="response" and (.path==$scep or .path==$cert) and .error==null and .entity_id!=null)] as $logins
   | {step:$op.step,request_id:$op.request_id,client_id:$op.client_id,entity_id:$op.entity_id,
      expected_auth:$request.expected_auth,challenge_present:$request.request.challenge_present,
      auth_paths:($logins|map(.path)|unique),
      auth_verified:($logins|length>0 and all(.path==(if $request.expected_auth=="cert" then $cert else $scep end)))}]' \
  > "$EVIDENCE_DIR/authentication-routing.json"
assert jq -e 'all(.auth_verified)' "$EVIDENCE_DIR/authentication-routing.json"
if [[ "$CERT_ONLY" == true ]]; then
  jq -n --slurpfile routing "$EVIDENCE_DIR/authentication-routing.json" --slurpfile requests "$EVIDENCE_DIR/request-results.jsonl" \
    '[$routing[0][] as $route | ($requests[]|select(.step==$route.step)) + $route]' > "$EVIDENCE_DIR/lifecycle-operations.json"
  jq -e -f "$SCRIPT_DIR/verify_scep_cert_only.jq" "$EVIDENCE_DIR/lifecycle-operations.json" > "$EVIDENCE_DIR/assertions.json"
  jq -s '. as $p | to_entries | map(.key as $i | {phase:.value.phase,clients:.value.clients,
    delta:(if $i==0 then 0 else .value.clients.clients-$p[$i-1].clients.clients end)})' \
    "$EVIDENCE_DIR/phases.jsonl" > "$EVIDENCE_DIR/phase-deltas.json"
  CERT_COMPARISON=$(jq -c '.observations+{tested:true}' "$EVIDENCE_DIR/assertions.json")
elif [[ "$SCEP_TEST_CERT_AUTH" == true ]]; then
  assert jq -e '[.[]|select(.expected_auth=="cert")]|length==4 and all(.challenge_present==false)' "$EVIDENCE_DIR/authentication-routing.json"
  jq -n --slurpfile ops "$EVIDENCE_DIR/operations.json" --slurpfile certs "$EVIDENCE_DIR/activity-after-cert-renew.json" \
    --slurpfile repeat "$EVIDENCE_DIR/activity-after-cert-repeat.json" --slurpfile base "$EVIDENCE_DIR/activity-after-challenge-negative.json" \
    --slurpfile negatives "$EVIDENCE_DIR/activity-after-cert-negatives.json" '
    def id($step): $ops[0][]|select(.step==$step)|.entity_id;
    {devices:["01","02","03"]|map(. as $i | {device:("device-"+$i),
       challenge_entity:id("device-"+$i),cert_entity:id("device-"+$i+"-cert-renewed"),
       same_entity:(id("device-"+$i)==id("device-"+$i+"-cert-renewed"))}),
     repeat_same_entity:(id("device-01-cert-renewed")==id("device-01-cert-renewed-again")),
     cert_transition_client_delta:($certs[0].data.total.clients-$base[0].data.total.clients),
     cert_repeat_client_delta:($repeat[0].data.total.clients-$certs[0].data.total.clients),
     negative_client_delta:($negatives[0].data.total.clients-$repeat[0].data.total.clients)}' \
    > "$EVIDENCE_DIR/cert-auth-comparison.json"
  CERT_COMPARISON=$(jq -c '.+{tested:true}' "$EVIDENCE_DIR/cert-auth-comparison.json")
fi

BEFORE_CERTS=$(jq '[.data.months[]?.counts.issued_certificates // 0]|add//0' "$EVIDENCE_DIR/certificates-before.json")
